function canonicalHookEvent(value) {
  const raw = String(value || '').trim();
  const normalized = raw.replace(/[_-]/g, '').toLowerCase();
  const aliases = {
    pretooluse: 'PreToolUse', posttooluse: 'PostToolUse', stop: 'Stop', agentstop: 'Stop',
    notification: 'Notification', sessionstart: 'SessionStart', sessionend: 'SessionEnd',
    userpromptsubmit: 'UserPromptSubmit', userpromptsubmitted: 'UserPromptSubmit',
    precompact: 'PreCompact', postcompact: 'PostCompact', subagentstop: 'SubagentStop',
    subagentstart: 'SubagentStart', permissionrequest: 'PermissionRequest',
    pretoolcall: 'PreToolUse', posttoolcall: 'PostToolUse', onsessionstart: 'SessionStart',
    onsessionend: 'SessionEnd', onsessionfinalize: 'SessionEnd', prellmcall: 'UserPromptSubmit',
  };
  return aliases[normalized] || raw;
}

function mapHookEvent(event, target) {
  return HOOK_EVENT_MAP[target]?.[canonicalHookEvent(event)] || null;
}

function normalizeMatcher(value) {
  const raw = String(value ?? '*').trim() || '*';
  if (raw.length > 256) return { supported: false, raw, patterns: [] };
  const parts = raw.split('|').map((item) => item.trim()).filter(Boolean);
  if (!parts.length || parts.some((item) => /[^A-Za-z0-9_.:/@*? -]/.test(item))) {
    return { supported: false, raw, patterns: [] };
  }
  return { supported: true, raw, patterns: unique(parts) };
}

